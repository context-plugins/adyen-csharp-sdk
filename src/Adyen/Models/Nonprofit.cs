using System.Collections.Generic;
using System.ComponentModel.DataAnnotations;
using System.Text.Json.Serialization;
using Adyen.Core.Models;

namespace Adyen.Models;

public record Nonprofit
{
    /// <summary>
    /// The causes that the nonprofit supports.
    /// </summary>
    [JsonPropertyName("causes")]
    [MinLength(1)]
    public required IReadOnlyList<NonprofitCause> Causes { get; init; }

    /// <summary>
    /// The description of the nonprofit.
    /// </summary>
    [JsonPropertyName("description")]
    public required string Description { get; init; }

    /// <summary>
    /// The goals of the nonprofit.
    /// </summary>
    [JsonPropertyName("goals")]
    [MinLength(1)]
    public required IReadOnlyList<string> Goals { get; init; }

    /// <summary>
    /// The unique identifier of the nonprofit organization. This value is generated by Adyen.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("id")]
    public string? Id { get; init; }

    /// <summary>
    /// The locales that the nonprofit supports, in <see href="https://en.wikipedia.org/wiki/IETF_language_tag">IETF BCP 47</see> format.
    /// </summary>
    [JsonPropertyName("locales")]
    [MinLength(1)]
    public required IReadOnlyList<string> Locales { get; init; }

    /// <summary>
    /// The URL to the logo of the nonprofit.
    /// </summary>
    [JsonPropertyName("logoUrl")]
    public required string LogoUrl { get; init; }

    /// <summary>
    /// The name of the nonprofit.
    /// </summary>
    [JsonPropertyName("name")]
    public required string Name { get; init; }

    /// <summary>
    /// The regions where the nonprofit operates, in <see href="https://en.wikipedia.org/wiki/ISO_3166-1_alpha-2">ISO 3166-1 alpha-2</see> format.
    /// </summary>
    [JsonPropertyName("regions")]
    [MinLength(1)]
    public required IReadOnlyList<string> Regions { get; init; }

    /// <summary>
    /// The URL to the terms and conditions of the nonprofit.
    /// </summary>
    [JsonPropertyName("termsAndConditionsUrl")]
    public required string TermsAndConditionsUrl { get; init; }

    /// <summary>
    /// The URL to the website of the nonprofit.
    /// </summary>
    [JsonPropertyName("website")]
    public required string Website { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}
