using System;
using System.Collections.Generic;
using System.Text.Json.Serialization;
using Adyen.Models.Enums;

namespace Adyen.Models;

public record DonationCampaign1
{
    /// <summary>
    /// The unique identifiers of the account holders associated with the donation campaign.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("accountHolderIds")]
    public IReadOnlyList<string>? AccountHolderIds { get; init; }

    /// <summary>
    /// The date and time when the campaign started, in <see href="https://en.wikipedia.org/wiki/ISO_8601">ISO 8601</see> format. For example, 2026-06-18T10:28:59.820+00:00
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("activatedAt")]
    public DateTimeOffset? ActivatedAt { get; init; }

    /// <summary>
    /// The date and time when the campaign stopped, in <see href="https://en.wikipedia.org/wiki/ISO_8601">ISO 8601</see> format.  For example, 2026-06-18T10:28:59.820+00:00.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("endedAt")]
    public DateTimeOffset? EndedAt { get; init; }

    /// <summary>
    /// The unique identifier of the donation campaign. This value is generated by Adyen.
    /// </summary>
    [JsonPropertyName("id")]
    public required string Id { get; init; }

    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("inPerson")]
    public InPersonDonationSettingsResponse? InPerson { get; init; }

    /// <summary>
    /// The name of the donation campaign.
    /// </summary>
    [JsonPropertyName("name")]
    public required string Name { get; init; }

    [JsonPropertyName("nonprofitCause")]
    public required DonationCampaignNonprofitCause NonprofitCause { get; init; }

    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("online")]
    public OnlineDonationSettingsResponse? Online { get; init; }

    [JsonPropertyName("status")]
    public required DonationCampaignStatus2 Status { get; init; }
}
