using System.Text.Json.Serialization;
using Adyen.Core.Models;

namespace Adyen.Models;

public record AchAccountIdentifier
{
    /// <summary>
    /// The last digits of the account number. If the accountNumber is tokenized, this field contains the last digits of the non-tokenized account number. This helps users verify the account without seeing the full number.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("accountLastDigits")]
    public string? AccountLastDigits { get; init; }

    /// <summary>
    /// The account number of the bank account.
    /// </summary>
    [JsonPropertyName("accountNumber")]
    public required string AccountNumber { get; init; }

    /// <summary>
    /// Indicates whether the account number is tokenized. A tokenized account number is a unique ID generated by a bank to protect the user's actual account number.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("isTokenized")]
    public bool? IsTokenized { get; init; }

    /// <summary>
    /// The <see href="https://en.wikipedia.org/wiki/ABA_routing_transit_number">routing number</see>, without separators or whitespace.
    /// </summary>
    [JsonPropertyName("routingNumber")]
    public required string RoutingNumber { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}
