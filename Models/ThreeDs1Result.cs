using System.Text.Json.Serialization;

namespace Adyen.Models;

public record ThreeDs1Result
{
    /// <summary>
    /// The cardholder authentication value (base64 encoded).
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("cavv")]
    public string? Cavv { get; init; }

    /// <summary>
    /// The CAVV algorithm used.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("cavvAlgorithm")]
    public string? CavvAlgorithm { get; init; }

    /// <summary>
    /// 3D Secure Electronic Commerce Indicator (ECI).
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("eci")]
    public string? Eci { get; init; }

    /// <summary>
    /// The authentication response from the ACS.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("threeDAuthenticatedResponse")]
    public string? ThreeDauthenticatedResponse { get; init; }

    /// <summary>
    /// Whether 3D Secure was offered or not.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("threeDOfferedResponse")]
    public string? ThreeDofferedResponse { get; init; }

    /// <summary>
    /// A unique transaction identifier generated by the MPI on behalf of the merchant to identify the 3D Secure transaction, in <c>Base64</c> encoding.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("xid")]
    public string? Xid { get; init; }
}
