using System.Collections.Generic;
using System.Text.Json.Serialization;
using Adyen.Models.Enums;

namespace Adyen.Models;

public record Store
{
    /// <summary>
    /// Reference to resources connected with the store.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("_links")]
    public Links7? Links { get; init; }

    /// <summary>
    /// The address of the store.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("address")]
    public StoreLocation1? Address { get; init; }

    /// <summary>
    /// The unique identifiers of the <see href="https://docs.adyen.com/api-explorer/#/legalentity/latest/post/businesslines__resParam_id">business lines</see> that the store is associated with.
    ///  If not specified, the business line of the merchant account is used. Required when there are multiple business lines under the merchant account.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("businessLineIds")]
    public IReadOnlyList<string>? BusinessLineIds { get; init; }

    /// <summary>
    /// The description of the store.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("description")]
    public string? Description { get; init; }

    /// <summary>
    /// The unique identifier of the store, used by certain payment methods and tax authorities.
    /// <para>
    /// Required for CNPJ in Brazil, in the format 00.000.000/0000-00 separated by dots, slashes, hyphens, or without separators.
    /// </para>
    /// <para>
    /// Optional for SIRET in France, up to 14 digits.
    /// </para>
    /// <para>
    /// Optional for Zip in Australia, up to 50 digits.
    /// </para>
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("externalReferenceId")]
    public string? ExternalReferenceId { get; init; }

    /// <summary>
    /// The unique identifier of the store. This value is generated by Adyen.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("id")]
    public string? Id { get; init; }

    /// <summary>
    /// The localized information of the store.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("localizedInformation")]
    public LocalizedInformation4? LocalizedInformation { get; init; }

    /// <summary>
    /// The unique identifier of the merchant account that the store belongs to.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("merchantId")]
    public string? MerchantId { get; init; }

    /// <summary>
    /// The phone number of the store, including '+' and country code in the <see href="https://en.wikipedia.org/wiki/E.164">E.164</see> format. If passed in a different format, we convert and validate the phone number against E.164.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("phoneNumber")]
    public string? PhoneNumber { get; init; }

    /// <summary>
    /// A reference to recognize the store by. Also known as the store code.
    ///  Allowed characters: lowercase and uppercase letters without diacritics, numbers 0 through 9, hyphen (-), and underscore (_)
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("reference")]
    public string? Reference { get; init; }

    /// <summary>
    /// The store name shown on the shopper's bank or credit card statement and on the shopper receipt.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("shopperStatement")]
    public string? ShopperStatement { get; init; }

    /// <summary>
    /// Rules for Adyen for Platforms merchants to split the transaction amount and fees.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("splitConfiguration")]
    public StoreSplitConfiguration1? SplitConfiguration { get; init; }

    /// <summary>
    /// The status of the store. Possible values are:
    /// <list type="bullet">
    ///   <item><description><b>active</b>. This value is assigned automatically when a store is created.</description></item>
    ///   <item><description><b>inactive</b>. The terminals under the store are blocked from accepting new transactions, but capturing outstanding transactions is still possible.</description></item>
    ///   <item><description><b>closed</b>. This status is irreversible. The terminals under the store are reassigned to the merchant inventory.</description></item>
    /// </list>
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("status")]
    public Status11? Status { get; init; }

    /// <summary>
    /// The sub-merchant data relevant for registered payment facilitators transacting on standalone terminals.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("subMerchantData")]
    public SubMerchantData1? SubMerchantData { get; init; }
}
